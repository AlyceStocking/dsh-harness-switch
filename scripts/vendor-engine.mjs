import { build } from 'esbuild';
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { writeFile, mkdir } from 'node:fs/promises';
import { resolve, join, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
const root = resolve(process.argv[2] || '../kimi-code');
const commit = 'c9f01f07388abc2cdca40c9c5267f58c65086710';
if (execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim() !== commit) throw new Error('Unexpected Kimi revision');
const packages = new Map();
for (const name of readdirSync(join(root, 'packages'))) {
  const dir = join(root, 'packages', name), file = join(dir, 'package.json');
  if (existsSync(file)) { const pkg = JSON.parse(readFileSync(file, 'utf8')); packages.set(pkg.name, { dir, pkg }); }
}
function resolveFile(path) {
  for (const candidate of [path, `${path}.ts`, `${path}.tsx`, `${path}.js`, join(path, 'index.ts')]) if (existsSync(candidate)) return candidate;
  throw new Error(`Cannot resolve ${path}`);
}
await mkdir('vendor/engine', { recursive: true });
const result = await build({
  stdin: { contents: "export { createKimiHarness } from '@moonshot-ai/kimi-code-sdk';", resolveDir: root },
  outfile: 'vendor/engine/index.mjs', bundle: true, platform: 'node', format: 'esm', target: 'node24', packages: 'external', metafile: true, logLimit: 4, tsconfigRaw: { compilerOptions: { experimentalDecorators: true } },
  banner: { js: `// Kimi Code ${commit}; MIT; ../KIMI-LICENSE. Generated by scripts/vendor-engine.mjs.\nimport { createRequire as __createRequire } from 'node:module';\nimport { fileURLToPath as __fileURLToPath } from 'node:url';\nimport { dirname as __pathDirname } from 'node:path';\nconst require = __createRequire(import.meta.url);\nconst __filename = __fileURLToPath(import.meta.url);\nconst __dirname = __pathDirname(__filename);` },
  plugins: [{ name: 'upstream-workspaces', setup(api) {
    api.onLoad({ filter: /bootstrapService\.ts$/ }, args => {
      const original = readFileSync(args.path, 'utf8');
      const needle = "this.cacheDir = join(options.homeDir, 'cache');";
      if (!original.includes(needle)) throw new Error('Upstream cache isolation patch no longer applies');
      return { contents: original.replace(needle, "this.cacheDir = join(options.homeDir, 'cache', 'dsh-harness-switch');"), loader: 'ts' };
    });
    api.onResolve({ filter: /^ajv\/dist\/(2019|2020)$/ }, args => ({ path: `${args.path}.js`, external: true }));
    api.onResolve({ filter: /^@moonshot-ai\// }, args => {
      const name = args.path.split('/').slice(0, 2).join('/'), entry = packages.get(name);
      if (!entry) throw new Error(`Missing workspace ${name}`);
      const sub = args.path.slice(name.length), key = sub ? `.${sub}` : '.';
      let target = entry.pkg.exports?.[key];
      if (!target && sub && entry.pkg.exports?.['./*']) {
        target = entry.pkg.exports['./*'];
        if (typeof target === 'object') target = target.default || target.import;
        target = target.replace('*', sub.slice(1));
      }
      if (typeof target === 'object') target = target.default || target.import;
      return { path: resolveFile(resolve(entry.dir, target || (sub ? `src${sub}` : 'src/index.ts'))) };
    });
    api.onResolve({ filter: /^#/ }, args => {
      let dir = dirname(args.importer);
      while (!existsSync(join(dir, 'package.json'))) { const parent = dirname(dir); if (parent === dir) throw new Error('Missing package root'); dir = parent; }
      const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
      const key = Object.keys(pkg.imports || {}).find(key => args.path.startsWith(key.replace('*', '')));
      if (!key) throw new Error(`Unknown alias ${args.path}`);
      return { path: resolveFile(resolve(dir, pkg.imports[key].replace('*', args.path.slice(key.length - 1)))) };
    });
    api.onResolve({ filter: /\?raw$/ }, args => ({ path: resolve(args.resolveDir, args.path.slice(0, -4)), namespace: 'raw' }));
    api.onLoad({ filter: /.*/, namespace: 'raw' }, args => ({ contents: `export default ${JSON.stringify(readFileSync(args.path, 'utf8'))}`, loader: 'js' }));
  } }],
});
const external = result.metafile.outputs['vendor/engine/index.mjs'].imports.filter(i => i.external && !i.path.startsWith('node:')).map(i => i.path);
await writeFile('vendor/engine/build-manifest.json', JSON.stringify({ commit, imports: external, sources: Object.keys(result.metafile.inputs).length,
  patches: [{ file: 'bootstrapService.ts', purpose: 'Isolate the exclusive query-index cache from a concurrently running Kimi CLI', from: "join(options.homeDir, 'cache')", to: "join(options.homeDir, 'cache', 'dsh-harness-switch')" }],
}, null, 2) + '\n');
console.log(JSON.stringify({ bytes: result.metafile.outputs['vendor/engine/index.mjs'].bytes, external }, null, 2));
