import { build } from 'esbuild';
import { mkdir, copyFile, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { execFileSync } from 'node:child_process';
const root = resolve(process.argv[2] || '../kimi-code');
const commit = 'c9f01f07388abc2cdca40c9c5267f58c65086710';
if (execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim() !== commit) throw new Error('Unexpected Kimi source revision');
await mkdir('vendor', { recursive: true });
for (const [name, entry] of Object.entries({ 'kimi-provider': 'kosong/src/providers/kimi.ts', 'kimi-oauth': 'oauth/src/index.ts' })) {
  await build({ entryPoints: [join(root, 'packages', entry)], outfile: `vendor/${name}.mjs`, bundle: true, platform: 'node', format: 'esm', target: 'node22', packages: 'external',
    alias: { '#': join(root, 'packages/kosong/src') }, banner: { js: `// Kimi Code ${commit}; MIT; see KIMI-LICENSE. Generated by scripts/vendor-kimi.mjs.` } });
}
await copyFile(join(root, 'LICENSE'), 'vendor/KIMI-LICENSE');
await copyFile(join(root, 'packages/agent-core-v2/src/app/agentProfileCatalog/system.md'), 'vendor/kimi-system.md');
await writeFile('vendor/provenance.json', JSON.stringify({ repository: 'https://github.com/MoonshotAI/kimi-code', commit, license: 'MIT' }, null, 2) + '\n');
